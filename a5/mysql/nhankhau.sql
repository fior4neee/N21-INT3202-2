  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE ipums_vn2019;

CREATE TABLE IF NOT EXISTS nhankhau (
  `SERIAL` BIGINT NOT NULL,
  `PERNUM` INT NOT NULL,
  `PERWT` DOUBLE NOT NULL,
  `RELATE` INT NOT NULL,
  `RELATED` INT NOT NULL,
  `AGE` INT NOT NULL,
